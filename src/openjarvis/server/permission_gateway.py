"""Autonomous Permission Gateway and Sovereign Execution Authorization Nexus.

Enables Sergio to execute complex operating system commands (PowerShell on Windows,
zsh on macOS, ADB on Android/iPhone bridges) autonomously in the background while
presenting clean, one-click authorization cards to the human sovereign.

The user never writes commands or terminal scripts: Sergio handles the technical execution
and the user simply clicks 'Conceder Permiso' or 'Denegar' from the visual app portal.
"""

from __future__ import annotations

import logging
import threading
import time
import uuid
from dataclasses import asdict, dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional

from fastapi import APIRouter, HTTPException
from pydantic import BaseModel

log = logging.getLogger("openjarvis.server.permission_gateway")

router = APIRouter(prefix="/v1/permisos", tags=["permisos"])


class RiskLevel(str, Enum):
    LOW = "bajo"          # Read-only telemetry, safe queries
    MEDIUM = "medio"      # PowerShell scripts, service restarts, device sync
    HIGH = "alto"         # File modifications, external hardware actuation
    CRITICAL = "critico"  # Financial transactions, account purge, master vault unlock


class PermissionStatus(str, Enum):
    PENDING = "pendiente"
    GRANTED = "concedido"
    DENIED = "denegado"
    EXECUTED = "ejecutado"
    EXPIRED = "expirado"


@dataclass
class PermissionRequest:
    """An execution request generated by Sergio waiting for human authorization."""

    request_id: str
    title: str
    command: str
    system_target: str  # powershell, macos, iphone_android, hardware, escrow
    explanation: str
    risk_level: RiskLevel
    status: PermissionStatus = PermissionStatus.PENDING
    created_at: float = field(default_factory=time.time)
    resolved_at: Optional[float] = None
    resolved_by: Optional[str] = None
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d["risk_level"] = self.risk_level.value
        d["status"] = self.status.value
        return d


class PermissionGatewayStore:
    """Thread-safe in-memory and persistent store for permission requests."""

    _instance: Optional[PermissionGatewayStore] = None

    def __init__(self) -> None:
        self._lock = threading.RLock()
        self._requests: Dict[str, PermissionRequest] = {}
        self._mode: str = "asistente_soberano"  # "asistente_soberano" | "estricto_total"
        self._events: Dict[str, threading.Event] = {}

    @classmethod
    def get_instance(cls) -> PermissionGatewayStore:
        if cls._instance is None:
            cls._instance = PermissionGatewayStore()
        return cls._instance

    def create_request(
        self,
        title: str,
        command: str,
        system_target: str,
        explanation: str,
        risk_level: RiskLevel = RiskLevel.MEDIUM,
        metadata: Optional[Dict[str, Any]] = None,
    ) -> PermissionRequest:
        """Create a new permission authorization request."""
        req_id = f"perm-{int(time.time())}-{uuid.uuid4().hex[:6]}"
        req = PermissionRequest(
            request_id=req_id,
            title=title,
            command=command,
            system_target=system_target,
            explanation=explanation,
            risk_level=risk_level,
            metadata=metadata or {},
        )

        with self._lock:
            # If mode is sovereign and risk is low, auto-approve immediately
            if self._mode == "asistente_soberano" and risk_level == RiskLevel.LOW:
                req.status = PermissionStatus.GRANTED
                req.resolved_at = time.time()
                req.resolved_by = "auto_soberano_bajo_riesgo"
                log.info("Permiso auto-concedido (Bajo Riesgo): %s", title)

            self._requests[req_id] = req
            self._events[req_id] = threading.Event()

        return req

    def grant_permission(self, request_id: str, resolved_by: str = "usuario_portal") -> bool:
        """Grant authorization for the pending request."""
        with self._lock:
            req = self._requests.get(request_id)
            if not req:
                return False
            req.status = PermissionStatus.GRANTED
            req.resolved_at = time.time()
            req.resolved_by = resolved_by
            event = self._events.get(request_id)
            if event:
                event.set()
            log.info("Permiso concedido por usuario: %s (%s)", req.title, request_id)
            return True

    def deny_permission(self, request_id: str, resolved_by: str = "usuario_portal") -> bool:
        """Deny authorization for the pending request."""
        with self._lock:
            req = self._requests.get(request_id)
            if not req:
                return False
            req.status = PermissionStatus.DENIED
            req.resolved_at = time.time()
            req.resolved_by = resolved_by
            event = self._events.get(request_id)
            if event:
                event.set()
            log.info("Permiso denegado por usuario: %s (%s)", req.title, request_id)
            return True

    def get_pending(self) -> List[Dict[str, Any]]:
        """List all pending permission requests awaiting user action."""
        with self._lock:
            pending = [
                r.to_dict()
                for r in self._requests.values()
                if r.status == PermissionStatus.PENDING
            ]
            pending.sort(key=lambda x: x["created_at"], reverse=True)
            return pending

    def get_all(self, limit: int = 50) -> List[Dict[str, Any]]:
        """List all recent permission requests."""
        with self._lock:
            all_reqs = [r.to_dict() for r in self._requests.values()]
            all_reqs.sort(key=lambda x: x["created_at"], reverse=True)
            return all_reqs[:limit]

    def set_mode(self, mode: str) -> None:
        with self._lock:
            if mode in ("asistente_soberano", "estricto_total"):
                self._mode = mode

    def get_mode(self) -> str:
        with self._lock:
            return self._mode


def get_permission_gateway_store() -> PermissionGatewayStore:
    return PermissionGatewayStore.get_instance()


# -- API Router Endpoints ----------------------------------------------------


class PermissionActionBody(BaseModel):
    operador: str = "usuario_web"


class PermissionModeBody(BaseModel):
    modo: str


class CreateSimulatedPermissionBody(BaseModel):
    titulo: str
    comando: str
    sistema: str = "powershell"
    explicacion: str
    riesgo: str = "medio"


@router.get("/pendientes")
def get_pending_permissions() -> Dict[str, Any]:
    """List pending permission requests that require human click to proceed."""
    store = get_permission_gateway_store()
    pending = store.get_pending()
    return {
        "pendientes": pending,
        "total_pendientes": len(pending),
        "modo_autorizacion": store.get_mode(),
    }


@router.get("/historial")
def get_permission_history(limit: int = 30) -> Dict[str, Any]:
    """List historical permission requests and their resolution status."""
    store = get_permission_gateway_store()
    return {
        "historial": store.get_all(limit=limit),
        "modo_autorizacion": store.get_mode(),
    }


@router.post("/{request_id}/conceder")
def grant_permission_endpoint(request_id: str, body: Optional[PermissionActionBody] = None) -> Dict[str, Any]:
    """Grant approval for Sergio to execute the requested system command."""
    store = get_permission_gateway_store()
    operador = body.operador if body else "usuario_web"
    success = store.grant_permission(request_id, resolved_by=operador)
    if not success:
        raise HTTPException(404, f"No se encontró la solicitud de permiso '{request_id}'.")
    return {
        "ok": True,
        "request_id": request_id,
        "mensaje": "Permiso concedido exitosamente. Sergio ejecutando tarea en segundo plano.",
        "estado": PermissionStatus.GRANTED.value,
    }


@router.post("/{request_id}/denegar")
def deny_permission_endpoint(request_id: str, body: Optional[PermissionActionBody] = None) -> Dict[str, Any]:
    """Deny approval for the requested system command."""
    store = get_permission_gateway_store()
    operador = body.operador if body else "usuario_web"
    success = store.deny_permission(request_id, resolved_by=operador)
    if not success:
        raise HTTPException(404, f"No se encontró la solicitud de permiso '{request_id}'.")
    return {
        "ok": True,
        "request_id": request_id,
        "mensaje": "Permiso denegado. Sergio abortó la operación solicitada.",
        "estado": PermissionStatus.DENIED.value,
    }


@router.post("/modo")
def set_permission_mode_endpoint(body: PermissionModeBody) -> Dict[str, Any]:
    """Configure authorization mode: 'asistente_soberano' (smart auto-approve low risk) or 'estricto_total'."""
    store = get_permission_gateway_store()
    if body.modo not in ("asistente_soberano", "estricto_total"):
        raise HTTPException(400, "Modo inválido. Opciones: 'asistente_soberano', 'estricto_total'.")
    store.set_mode(body.modo)
    return {
        "ok": True,
        "modo_anterior": store.get_mode(),
        "modo_nuevo": body.modo,
    }


@router.post("/solicitar-ejemplo")
def create_sample_permission_endpoint(body: CreateSimulatedPermissionBody) -> Dict[str, Any]:
    """Helper to simulate an autonomous command permission request from Sergio."""
    store = get_permission_gateway_store()
    risk_map = {
        "bajo": RiskLevel.LOW,
        "medio": RiskLevel.MEDIUM,
        "alto": RiskLevel.HIGH,
        "critico": RiskLevel.CRITICAL,
    }
    risk = risk_map.get(body.riesgo.lower(), RiskLevel.MEDIUM)
    req = store.create_request(
        title=body.titulo,
        command=body.comando,
        system_target=body.sistema,
        explanation=body.explicacion,
        risk_level=risk,
    )
    return {"ok": True, "solicitud": req.to_dict()}


